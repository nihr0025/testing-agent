import logging
from typing import Dict, Any, List, Optional
from backend.services.ai_service import ai_service
from backend.database.db import save_scenarios, update_agent_status

logger = logging.getLogger("testing_platform.agent2_scenario")

class TestScenarioGenerationAgent:
    """
    AGENT 2: TEST SCENARIO GENERATION AGENT
    Responsibilities:
    1. Consume requirements generated by Agent 1.
    2. In Basic Mode: Generates Functional, Negative, and Navigation scenarios using predefined templates.
    3. In AI Mode: Generates comprehensive scenarios via Centralized Gemini Execution Engine or OpenAI.
    4. Handles transient errors with exponential backoff, jitter, and Retry-After support.
    5. Records selected vs actual model metadata and preserves requirement traceability.
    """
    def __init__(self, run_id: str):
        self.run_id = run_id
        self.agent_name = "scenario_agent"

    def execute(
        self,
        requirements: List[Dict[str, Any]],
        generation_mode: str = "basic",
        ai_model: Optional[str] = None,
        alternative_models: Optional[List[str]] = None
    ) -> List[Dict[str, Any]]:
        logger.info(
            f"[{self.run_id}] Agent 2: Generating scenarios from {len(requirements)} requirements "
            f"({generation_mode.upper()} mode, Model: {ai_model or 'default'})..."
        )
        update_agent_status(self.run_id, self.agent_name, "RUNNING")

        try:
            if not requirements:
                raise ValueError("No requirements supplied to Test Scenario Generation Agent.")

            scenarios = ai_service.generate_scenarios(
                requirements,
                mode=generation_mode,
                model_name=ai_model,
                alternative_models=alternative_models,
                run_id=self.run_id
            )

            meta = ai_service.last_execution_metadata or {}
            selected_model = meta.get("selected_model", ai_model or "")
            actual_model = meta.get("actual_model", ai_model or "")
            retries_count = meta.get("retries_count", 0)
            models_attempted = meta.get("models_attempted", [ai_model] if ai_model else [])

            # Persist to database
            save_scenarios(
                self.run_id,
                scenarios,
                generation_mode=generation_mode,
                ai_provider=generation_mode,
                ai_model=actual_model or ""
            )

            update_agent_status(
                self.run_id,
                self.agent_name,
                "COMPLETED",
                output_data={
                    "mode": generation_mode,
                    "selected_model": selected_model,
                    "actual_model": actual_model,
                    "retries_count": retries_count,
                    "models_attempted": models_attempted,
                    "count": len(scenarios),
                    "scenarios": scenarios
                },
                retries_count=retries_count,
                selected_model=selected_model,
                actual_model=actual_model,
                models_attempted=models_attempted
            )
            logger.info(f"[{self.run_id}] Agent 2: Generated {len(scenarios)} scenarios (Actual Model: {actual_model}, Retries: {retries_count}).")
            return scenarios

        except Exception as e:
            err = f"Scenario generation failed: {str(e)}"
            error_cat = getattr(e, "error_category", "ExecutionError")
            attempted = getattr(e, "models_attempted", [ai_model] if ai_model else [])
            retries = getattr(e, "total_retries", 0)
            logger.error(f"[{self.run_id}] Agent 2 error: {err}")
            update_agent_status(
                self.run_id,
                self.agent_name,
                "FAILED",
                error_message=err,
                retries_count=retries,
                selected_model=ai_model or "",
                models_attempted=attempted,
                error_category=error_cat
            )
            raise
