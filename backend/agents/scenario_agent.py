import logging
from typing import Dict, Any, List
from backend.services.ai_service import ai_service
from backend.database.db import save_scenarios, update_agent_status

logger = logging.getLogger("testing_platform.agent2_scenario")

class TestScenarioGenerationAgent:
    """
    AGENT 2: TEST SCENARIO GENERATION AGENT
    Responsibilities:
    1. Consume requirements generated by Agent 1.
    2. In Basic Mode: Generates Functional, Negative, and Navigation scenarios using predefined Python templates.
    3. In AI Mode: Generates comprehensive scenarios via OpenAI.
    4. Avoids duplicates and maps every scenario to its corresponding requirement ID.
    """
    def __init__(self, run_id: str):
        self.run_id = run_id
        self.agent_name = "scenario_agent"

    def execute(self, requirements: List[Dict[str, Any]], generation_mode: str = "basic") -> List[Dict[str, Any]]:
        logger.info(f"[{self.run_id}] Agent 2: Generating scenarios from {len(requirements)} requirements ({generation_mode.upper()} mode)...")
        update_agent_status(self.run_id, self.agent_name, "RUNNING")

        try:
            if not requirements:
                raise ValueError("No requirements supplied to Test Scenario Generation Agent.")

            scenarios = ai_service.generate_scenarios(requirements, mode=generation_mode)

            # Persist to database
            save_scenarios(self.run_id, scenarios, generation_mode=generation_mode)
            update_agent_status(
                self.run_id,
                self.agent_name,
                "COMPLETED",
                output_data={
                    "mode": generation_mode,
                    "count": len(scenarios),
                    "scenarios": scenarios
                }
            )
            logger.info(f"[{self.run_id}] Agent 2: Generated {len(scenarios)} scenarios.")
            return scenarios

        except Exception as e:
            err = f"Scenario generation failed: {str(e)}"
            logger.error(f"[{self.run_id}] Agent 2 error: {err}")
            update_agent_status(self.run_id, self.agent_name, "FAILED", error_message=err)
            raise RuntimeError(err)
