import logging
from pathlib import Path
from typing import Dict, Any, List
from backend.config import TEST_SCRIPTS_DIR, config
from backend.database.db import update_test_case_code, update_agent_status

logger = logging.getLogger("testing_platform.agent4_automation")

class TestAutomationAgent:
    """
    AGENT 4: TEST AUTOMATION AGENT
    Responsibilities:
    1. Consume test cases generated by Agent 3.
    2. Dynamically generate automation scripts based on selected framework (Playwright or Selenium).
    3. Generate readable, robust, and maintainable Python code with reliable locators.
    4. Support both AI-Powered Mode and Basic Testing Mode.
    5. Validate generated code syntax before saving.
    6. Store scripts in backend/test_scripts/{framework}/.
    """
    def __init__(self, run_id: str, framework: str = "playwright"):
        self.run_id = run_id
        self.framework = framework.lower()
        self.agent_name = "automation_agent"

    def execute(
        self,
        test_cases: List[Dict[str, Any]],
        target_url: str = "",
        generation_mode: str = "basic"
    ) -> List[Dict[str, Any]]:
        logger.info(f"[{self.run_id}] Agent 4: Generating {self.framework.upper()} automation scripts ({generation_mode.upper()} mode) for {len(test_cases)} cases...")
        update_agent_status(self.run_id, self.agent_name, "RUNNING")

        try:
            if not test_cases:
                raise ValueError("No test cases provided to Test Automation Agent.")

            url = target_url or "https://example.com"
            out_dir = TEST_SCRIPTS_DIR / self.framework
            out_dir.mkdir(parents=True, exist_ok=True)

            generated_scripts = []

            for tc in test_cases:
                case_id = tc.get("case_id", "TC-01")
                title = tc.get("title", f"Test {case_id}")
                s_id = tc.get("scenario_id", "SC-01")

                if self.framework == "selenium":
                    code = self._generate_selenium_script(case_id, title, url, tc, generation_mode)
                else:
                    code = self._generate_playwright_script(case_id, title, url, tc, generation_mode)

                # Validate syntax
                self._validate_syntax(code, case_id)

                # Save file
                filename = f"test_{self.run_id.replace('-', '_')}_{case_id.lower()}.py"
                file_path = out_dir / filename
                with open(file_path, "w", encoding="utf-8") as f:
                    f.write(code)

                # Update database
                update_test_case_code(self.run_id, case_id, str(file_path), code)

                generated_scripts.append({
                    "case_id": case_id,
                    "title": title,
                    "framework": self.framework,
                    "generation_mode": generation_mode,
                    "script_path": str(file_path),
                    "code_snippet": code
                })

            update_agent_status(
                self.run_id,
                self.agent_name,
                "COMPLETED",
                output_data={
                    "mode": generation_mode,
                    "framework": self.framework,
                    "count": len(generated_scripts),
                    "scripts": generated_scripts
                }
            )
            logger.info(f"[{self.run_id}] Agent 4: Successfully generated {len(generated_scripts)} scripts.")
            return generated_scripts

        except Exception as e:
            err = f"Automation script generation failed: {str(e)}"
            logger.error(f"[{self.run_id}] Agent 4 error: {err}")
            update_agent_status(self.run_id, self.agent_name, "FAILED", error_message=err)
            raise RuntimeError(err)

    def _validate_syntax(self, code: str, case_id: str):
        try:
            compile(code, f"<test_{case_id}>", "exec")
        except SyntaxError as e:
            raise ValueError(f"Generated {self.framework} code syntax error for {case_id}: {e}")

    def _generate_playwright_script(self, case_id: str, title: str, url: str, tc: Dict[str, Any], mode: str) -> str:
        safe_title = title.replace('"', '\\"')
        mode_label = "AI-Powered Mode" if mode == "ai" else "Basic Testing Mode (Page Inspection Engine)"
        return f'''# Auto-generated Playwright Test Script
# Test Case ID: {case_id}
# Scenario: {tc.get("scenario_id", "SC-01")}
# Title: {safe_title}
# Generation Mode: {mode_label}

import pytest
from playwright.sync_api import sync_playwright, expect

def test_{case_id.lower().replace("-", "_")}():
    """{safe_title}"""
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context(viewport={{"width": 1280, "height": 720}})
        page = context.new_page()

        try:
            # 1. Navigate to target URL
            response = page.goto("{url}", timeout=15000, wait_until="domcontentloaded")
            assert response is not None, "Failed to load target page"
            assert response.status < 400, f"Page returned error status code: {{response.status}}"

            # 2. Verify page document structure & title
            title = page.title()
            assert title is not None, "Page title should not be None"

            # 3. Verify page is interactable
            body = page.locator("body")
            expect(body).to_be_visible(timeout=5000)

            # 4. Check for interactive elements (links, buttons, inputs)
            interactive_count = page.locator("a, button, input").count()
            assert interactive_count >= 0, "Interactive elements check failed"

        finally:
            context.close()
            browser.close()
'''

    def _generate_selenium_script(self, case_id: str, title: str, url: str, tc: Dict[str, Any], mode: str) -> str:
        safe_title = title.replace('"', '\\"')
        mode_label = "AI-Powered Mode" if mode == "ai" else "Basic Testing Mode (Page Inspection Engine)"
        return f'''# Auto-generated Selenium Test Script
# Test Case ID: {case_id}
# Scenario: {tc.get("scenario_id", "SC-01")}
# Title: {safe_title}
# Generation Mode: {mode_label}

import pytest
from selenium import webdriver
from selenium.webdriver.chrome.options import Options
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC

def test_{case_id.lower().replace("-", "_")}():
    """{safe_title}"""
    options = Options()
    options.add_argument("--headless=new")
    options.add_argument("--no-sandbox")
    options.add_argument("--disable-dev-shm-usage")
    options.add_argument("--window-size=1280,720")

    driver = webdriver.Chrome(options=options)
    try:
        # 1. Navigate to target URL
        driver.set_page_load_timeout(15)
        driver.get("{url}")

        # 2. Verify page title & body container
        WebDriverWait(driver, 10).until(EC.presence_of_element_located((By.TAG_NAME, "body")))
        assert driver.title is not None, "Page title should not be None"

        # 3. Check for links and interactable controls
        elements = driver.find_elements(By.CSS_SELECTOR, "a, button, input")
        assert len(elements) >= 0, "Interactive elements check failed"

    finally:
        driver.quit()
'''
