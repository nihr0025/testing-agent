import logging
from typing import Dict, Any, List, Optional
from backend.services.ai_service import ai_service
from backend.database.db import save_test_cases, update_agent_status

logger = logging.getLogger("testing_platform.agent3_testcase")

class TestCaseDesignAgent:
    """
    AGENT 3: TEST CASE DESIGN AGENT
    Responsibilities:
    1. Consume scenarios generated by Agent 2.
    2. Convert each scenario into detailed step-by-step test cases.
    3. Generate preconditions, test data, execution steps, expected results.
    4. Supports Centralized Gemini Execution Engine with exponential backoff & failover.
    5. Maintain traceability to original requirements and scenarios.
    """
    def __init__(self, run_id: str, framework: str = "playwright"):
        self.run_id = run_id
        self.framework = framework
        self.agent_name = "testcase_agent"

    def execute(
        self,
        scenarios: List[Dict[str, Any]],
        generation_mode: str = "basic",
        ai_model: Optional[str] = None,
        alternative_models: Optional[List[str]] = None
    ) -> List[Dict[str, Any]]:
        logger.info(
            f"[{self.run_id}] Agent 3: Designing test cases from {len(scenarios)} scenarios "
            f"({generation_mode.upper()} mode, Model: {ai_model or 'default'})..."
        )
        update_agent_status(self.run_id, self.agent_name, "RUNNING")

        try:
            if not scenarios:
                raise ValueError("No scenarios supplied to Test Case Design Agent.")

            test_cases = ai_service.generate_test_cases(
                scenarios,
                mode=generation_mode,
                model_name=ai_model,
                alternative_models=alternative_models,
                run_id=self.run_id
            )

            meta = ai_service.last_execution_metadata or {}
            selected_model = meta.get("selected_model", ai_model or "")
            actual_model = meta.get("actual_model", ai_model or "")
            retries_count = meta.get("retries_count", 0)
            models_attempted = meta.get("models_attempted", [ai_model] if ai_model else [])

            # Persist to database
            save_test_cases(
                self.run_id,
                test_cases,
                framework=self.framework,
                generation_mode=generation_mode,
                ai_provider=generation_mode,
                ai_model=actual_model or ""
            )

            update_agent_status(
                self.run_id,
                self.agent_name,
                "COMPLETED",
                output_data={
                    "mode": generation_mode,
                    "selected_model": selected_model,
                    "actual_model": actual_model,
                    "retries_count": retries_count,
                    "models_attempted": models_attempted,
                    "framework": self.framework,
                    "count": len(test_cases),
                    "test_cases": test_cases
                },
                retries_count=retries_count,
                selected_model=selected_model,
                actual_model=actual_model,
                models_attempted=models_attempted
            )
            logger.info(f"[{self.run_id}] Agent 3: Created {len(test_cases)} test cases (Actual Model: {actual_model}, Retries: {retries_count}).")
            return test_cases

        except Exception as e:
            err = f"Test case design failed: {str(e)}"
            error_cat = getattr(e, "error_category", "ExecutionError")
            attempted = getattr(e, "models_attempted", [ai_model] if ai_model else [])
            retries = getattr(e, "total_retries", 0)
            logger.error(f"[{self.run_id}] Agent 3 error: {err}")
            update_agent_status(
                self.run_id,
                self.agent_name,
                "FAILED",
                error_message=err,
                retries_count=retries,
                selected_model=ai_model or "",
                models_attempted=attempted,
                error_category=error_cat
            )
            raise
