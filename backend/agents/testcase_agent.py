import logging
from typing import Dict, Any, List
from backend.services.ai_service import ai_service
from backend.database.db import save_test_cases, update_agent_status

logger = logging.getLogger("testing_platform.agent3_testcase")

class TestCaseDesignAgent:
    """
    AGENT 3: TEST CASE DESIGN AGENT
    Responsibilities:
    1. Consume scenarios generated by Agent 2.
    2. Convert each scenario into detailed step-by-step test cases.
    3. Generate preconditions, test data, execution steps, expected results.
    4. Supports both AI Mode and Basic Testing Mode.
    5. Maintain traceability to original requirements and scenarios.
    """
    def __init__(self, run_id: str, framework: str = "playwright"):
        self.run_id = run_id
        self.framework = framework
        self.agent_name = "testcase_agent"

    def execute(self, scenarios: List[Dict[str, Any]], generation_mode: str = "basic") -> List[Dict[str, Any]]:
        logger.info(f"[{self.run_id}] Agent 3: Designing test cases from {len(scenarios)} scenarios ({generation_mode.upper()} mode)...")
        update_agent_status(self.run_id, self.agent_name, "RUNNING")

        try:
            if not scenarios:
                raise ValueError("No scenarios supplied to Test Case Design Agent.")

            test_cases = ai_service.generate_test_cases(scenarios, mode=generation_mode)

            # Persist to database
            save_test_cases(self.run_id, test_cases, framework=self.framework, generation_mode=generation_mode)
            update_agent_status(
                self.run_id,
                self.agent_name,
                "COMPLETED",
                output_data={
                    "mode": generation_mode,
                    "framework": self.framework,
                    "count": len(test_cases),
                    "test_cases": test_cases
                }
            )
            logger.info(f"[{self.run_id}] Agent 3: Created {len(test_cases)} test cases.")
            return test_cases

        except Exception as e:
            err = f"Test case design failed: {str(e)}"
            logger.error(f"[{self.run_id}] Agent 3 error: {err}")
            update_agent_status(self.run_id, self.agent_name, "FAILED", error_message=err)
            raise RuntimeError(err)
